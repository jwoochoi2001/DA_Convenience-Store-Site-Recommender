def render(fig_fn) -> list[str]:
    out = []
    out.append("## 14. 발표 자료 장표별 시각화와 근거")
    out.append("")
    out.append("5~8절의 코드 그림으로 설명되지 않던 발표 장표(번호는 `편의점_입지추천_최종발표` PDF의 슬라이드 번호)를 정리했다. **그림은 발표 PDF에서 해당 장표의 본문만 잘라낸 이미지**(`eda_output/deck/slideNN.png`)이고, 설명의 숫자는 발표 자료에 적힌 값이다. 이 저장소 코드가 같은 값을 다시 만드는지는 9절에서 확인한다.")
    out.append("")
    for n, title, part, bullets in SLIDES:
        out.append(f"### 슬라이드 {n} · {title}")
        out.append(f"*{part}*")
        out.append("")
        out.append(fig_fn(f"eda_output/deck/slide{n:02d}.png", f"슬라이드 {n}"))
        out.append("")
        for b in bullets:
            out.append(f"- {b}")
        out.append("")
    return out
